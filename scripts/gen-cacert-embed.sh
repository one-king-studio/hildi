#!/usr/bin/env bash
# Generate build/gen/cacert_embedded.c from deps/cacert/cacert.pem.
#
# The CA bundle is compiled into the binary (not shipped beside it), so the
# release stays a single self-contained file. The generated source defines
# hildi_ca_pem()/hildi_ca_pem_len() (see src/hildi_tls_shim.h); the
# array ends with a NUL because mbedTLS PEM parsing expects one and the length
# includes it.
#
# Usage: scripts/gen-cacert-embed.sh

set -euo pipefail

cd "$(dirname "$0")/.." || exit 1

PEM="deps/cacert/cacert.pem"
OUT="build/gen/cacert_embedded.c"

if [ ! -f "$PEM" ]; then
  echo "cacert: $PEM missing; run scripts/fetch-cacert.sh" >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT")"

{
  echo '/* Generated by scripts/gen-cacert-embed.sh from deps/cacert/cacert.pem.'
  echo '   Do not edit. */'
  echo '#include "hildi_tls_shim.h"'
  echo
  echo 'static const unsigned char kCaPem[] = {'
  od -An -tu1 -v "$PEM" |
    awk '{ for (i = 1; i <= NF; i++) { printf "%s,", $i; if (++n % 16 == 0) printf "\n" } }'
  echo '0};'
  echo
  echo 'const unsigned char *hildi_ca_pem(void) { return kCaPem; }'
  echo 'unsigned hildi_ca_pem_len(void) { return (unsigned)sizeof(kCaPem); }'
} > "$OUT"

echo "cacert: wrote $OUT ($(wc -c < "$PEM" | tr -d ' ') bytes embedded)"
